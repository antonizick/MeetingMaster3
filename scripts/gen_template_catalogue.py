#!/usr/bin/env python3
"""Generate docs/user-guide/template-catalogue.md from the built-in template files.

    uv run python scripts/gen_template_catalogue.py          # rewrite the file
    uv run python scripts/gen_template_catalogue.py --check  # exit 1 if it is out of date (CI)

The catalogue is derived only from the files in ``src/meetingmaster3/starter_templates/``, so it
never drifts from what ships.
"""

from __future__ import annotations

import sys
from pathlib import Path

from meetingmaster3.templates.loader import builtin_files
from meetingmaster3.templates.schema import Template, parse_template_file

TARGET = Path(__file__).parents[1] / "docs" / "user-guide" / "template-catalogue.md"
DEFAULT_ID = "executive-summary"
INTRO = """\
# Template catalogue

<!-- Generated by scripts/gen_template_catalogue.py from the built-in templates. Do not edit by
hand: edit the template files and run `uv run python scripts/gen_template_catalogue.py`. -->

MeetingMaster3 ships {count} built-in templates. Pick one when you upload a recording (the
default is **{default}**); see [`templates.md`](templates.md) for how templates work and how to
change them, and [`../dev-guide/template-format.md`](../dev-guide/template-format.md) for the file
format.

| Template | `id` | Use it for |
|---|---|---|
{rows}
"""


def load_templates() -> list[Template]:
    templates = []
    for path in builtin_files():
        report = parse_template_file(path)
        if report.template is None:
            raise SystemExit(f"{path.name} is invalid: {[str(i) for i in report.issues]}")
        templates.append(report.template)
    return sorted(templates, key=lambda t: t.name.casefold())


def section_line(template: Template, section_id: str) -> str:
    section = template.section(section_id)
    assert section is not None
    note = " (checkbox tasks)" if section.format == "tasks" else ""
    return f"{section.title}{note}"


def render(templates: list[Template]) -> str:
    rows = "\n".join(f"| [{t.name}](#{anchor(t)}) | `{t.id}` | {t.description} |" for t in templates)
    parts = [INTRO.format(count=len(templates), default=DEFAULT_ID, rows=rows)]
    for t in templates:
        parts.append(f"## {t.name}\n")
        parts.append(f"`{t.id}`" + (" (the default)" if t.id == DEFAULT_ID else ""))
        parts.append(f"\n{t.description}\n")
        if t.tags:
            parts.append(f"**Library tags:** {', '.join(t.tags)}\n")
        parts.append("**Sections, in order:**\n")
        parts.extend(f"{i}. {section_line(t, s.id)}" for i, s in enumerate(t.sections, 1))
        if not t.params.ai_recommendations:
            parts.append(
                "\nThis template deliberately has no **AI Recommendations** section: "
                "it is a formal record."
            )
        parts.append("")
    return "\n".join(parts).rstrip("\n") + "\n"


def anchor(template: Template) -> str:
    """The GitHub / Obsidian heading anchor of the template's name."""
    kept = "".join(c for c in template.name.lower() if c.isalnum() or c in " -")
    return kept.replace(" ", "-")


def main(argv: list[str]) -> int:
    text = render(load_templates())
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            print(f"{TARGET} is out of date. Run: uv run python scripts/gen_template_catalogue.py")
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"Wrote {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
