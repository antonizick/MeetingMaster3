@dataclass
class Span:
    start: datetime
    end: datetime


def phase_end(p: PhaseRecord, as_of: datetime) -> datetime:
    if p.finish and p.status == "complete":
        return p.finish.moment.at
    if p.status == "complete" and p.merged:
        return p.merged.moment.at
    return as_of


def activity(tl: Timeline, gap: timedelta) -> list[Span]:
    """Busy spans. A merge tail counts only if the merge came within ``gap`` of the finish;
    a later merge is written in the bar's label instead of stretching a session over idle time."""
    assert tl.as_of is not None
    as_of = tl.as_of.at
    spans: list[Span] = []
    for p in tl.phases:
        assert p.start is not None
        end = phase_end(p, as_of)
        if p.merged and end < p.merged.moment.at <= end + gap:
            end = p.merged.moment.at
        spans.append(Span(p.start.moment.at, max(end, p.start.moment.at)))
    for it in tl.planning:
        if it.start and it.end:
            spans.append(Span(it.start.moment.at, max(it.end.moment.at, it.start.moment.at)))
    return spans


def sessions(spans: list[Span], gap: timedelta) -> list[Span]:
    """Merge activity into working sessions; a gap longer than ``gap`` starts a new one."""
    merged: list[Span] = []
    for s in sorted(spans, key=lambda s: (s.start, s.end)):
        if merged and s.start - merged[-1].end <= gap:
            merged[-1].end = max(merged[-1].end, s.end)
        else:
            merged.append(Span(s.start, s.end))
    return merged


def active_time(p: PhaseRecord, as_of: datetime) -> tuple[timedelta, timedelta]:
    assert p.start is not None
    end = phase_end(p, as_of)
    total = max(end - p.start.moment.at, timedelta(0))
    waited = timedelta(0)
    for w in p.waits:
        w_end = w.end.moment.at if w.end else as_of
        lo = max(w.start.moment.at, p.start.moment.at)
        hi = min(w_end, end)
        if hi > lo:
            waited += hi - lo
    return total - waited, waited


