def replace_block(text: str, block: str, name: str, after_line: int = 0) -> str:
    lines = text.split("\n")
    starts = [i for i, ln in enumerate(lines) if ln.strip().startswith(_START_PREFIX)]
    ends = [i for i, ln in enumerate(lines) if ln.strip() == END_MARKER]
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        raise TimelineError(
            f"{name}: expected one '{_START_PREFIX} …' line followed by one '{END_MARKER}' line"
        )
    if starts[0] < after_line:
        raise TimelineError(f"{name}: the timeline markers must come after the phase table")
    s, e = starts[0], ends[0]
    new = [*lines[:s], START_MARKER, *block.split("\n"), *lines[e:]]
    return "\n".join(new)


def has_markers(text: str) -> bool:
    return any(ln.strip().startswith(_START_PREFIX) for ln in text.split("\n"))


def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as fh:
            fh.write(text)
        if path.exists():
            os.chmod(tmp, path.stat().st_mode & 0o777)
        else:
            os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def final_report(repo: Path, prefix: str | None) -> Path | None:
    names = [f"{prefix}_FINAL-REPORT.md", f"{prefix}_FINAL_REPORT.md"] if prefix else []
    names += ["FINAL-REPORT.md", "FINAL_REPORT.md"]
    for n in names:
        p = repo / "docs" / n
        if p.is_file():
            return p
    return None


def outputs(repo: Path, gap_minutes: int, vault_note: Path | None) -> dict[Path, str]:
    """Every output file and the full text it should have."""
    tl, plan, _lines, table_end = build_timeline(repo)
    svg_path = repo / "docs" / (f"{tl.prefix}_TIMELINE.svg" if tl.prefix else "TIMELINE.svg")
    result: dict[Path, str] = {svg_path: render_svg(tl, gap_minutes)}
    plan_text = plan.read_text(encoding="utf-8")
    rel = os.path.relpath(svg_path, plan.parent).replace(os.sep, "/")
    result[plan] = replace_block(
        plan_text, render_block(tl, gap_minutes, rel), plan.name, after_line=table_end + 1
    )
    report = final_report(repo, tl.prefix)
    if report is not None:
        rtext = report.read_text(encoding="utf-8")
        if has_markers(rtext):
            rrel = os.path.relpath(svg_path, report.parent).replace(os.sep, "/")
            result[report] = replace_block(rtext, render_block(tl, gap_minutes, rrel), report.name)
    if vault_note is not None:
        if not vault_note.is_file():
            raise TimelineError(f"vault note not found: {vault_note}")
        vtext = vault_note.read_text(encoding="utf-8")
        result[vault_note] = replace_block(
            vtext, render_block(tl, gap_minutes, None), vault_note.name
        )
    return result


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="phase_timeline.py",
        description="Draw a phased project's timeline from its plan and git.",
    )
    ap.add_argument("--repo", type=Path, default=Path("."), help="repository root (default: .)")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="update the outputs in place")
    mode.add_argument("--check", action="store_true", help="exit 1 if any output is stale")
    mode.add_argument("--print", action="store_true", help="print the block (default)")
    ap.add_argument("--vault-note", type=Path, help="also update this note (no image)")
    ap.add_argument("--gap-minutes", type=int, default=60, help="idle gap to collapse (60)")
    args = ap.parse_args(argv)
    if args.gap_minutes < 1:
        print("phase_timeline: --gap-minutes must be at least 1", file=sys.stderr)
        return EXIT_USAGE
    repo = args.repo.resolve()
    try:
        if args.write or args.check:
            wanted = outputs(repo, args.gap_minutes, args.vault_note)
        else:
            tl, _plan, _lines, _end = build_timeline(repo)
            svg = f"docs/{tl.prefix}_TIMELINE.svg" if tl.prefix else "docs/TIMELINE.svg"
            sys.stdout.write(render_block(tl, args.gap_minutes, svg) + "\n")
            return 0
    except (TimelineError, OSError, UnicodeDecodeError) as exc:
        print(f"phase_timeline: {exc}", file=sys.stderr)
        return EXIT_USAGE
    stale = []
    for path, text in wanted.items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != text:
            stale.append(path)
    if args.check:
        if stale:
            names = ", ".join(_rel(p, repo) for p in stale)
            print(f"phase_timeline: timeline stale: {names} (run --write on main)", file=sys.stderr)
            return EXIT_STALE
        return 0
    for path in stale:
        atomic_write(path, wanted[path])
        print(f"phase_timeline: wrote {_rel(path, repo)}")
    if not stale:
        print("phase_timeline: up to date")
    return 0


def _rel(p: Path, repo: Path) -> str:
    try:
        return str(p.relative_to(repo))
    except ValueError:
        return str(p)


if __name__ == "__main__":
    sys.exit(main())
