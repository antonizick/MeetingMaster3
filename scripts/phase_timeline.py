_MERMAID_BAD = str.maketrans({":": " -", "#": "No.", ";": ",", "`": "", '"': "'", "\n": " "})


def mermaid_text(s: str) -> str:
    return re.sub(r"\s+", " ", s.translate(_MERMAID_BAD)).strip()


def _wall(at: datetime, off: timezone) -> str:
    return f"{at.astimezone(off):%Y-%m-%d %H:%M}"


def render_mermaid(tl: Timeline, gap_minutes: int) -> list[str]:
    assert tl.as_of is not None
    as_of = tl.as_of.at
    segs = sessions(activity(tl, timedelta(minutes=gap_minutes)), timedelta(minutes=gap_minutes))
    zone_of = _zone_lookup(tl)
    names = {
        int((v.moment.at.utcoffset() or timedelta(0)).total_seconds() // 60): v.moment.zone
        for p in tl.phases
        for v in (p.start,)
        if v
    }
    names.update(
        {
            int(
                (it.start.moment.at.utcoffset() or timedelta(0)).total_seconds() // 60
            ): it.start.moment.zone
            for it in tl.planning
            if it.start
        }
    )
    charts: list[str] = []
    for n, seg in enumerate(segs, 1):
        off = zone_of(seg.start)
        zname = names.get(int((off.utcoffset(None) or timedelta(0)).total_seconds() // 60), "local")
        title = (
            f"{tl.prefix or 'Project'} session {n}, {_wall(seg.start, off)} to "
            f"{_wall(seg.end, off)[11:]} {zname}"
        )
        lines = [
            "```mermaid",
            "gantt",
            "    title " + re.sub(r"\s+", " ", re.sub(r"[#;`]", "", title)).strip(),
            "    dateFormat YYYY-MM-DD HH:mm",
            "    axisFormat %H:%M",
        ]
        plan_lines = []
        for it in tl.planning:
            if not (it.start and it.end) or not (seg.start <= it.start.moment.at <= seg.end):
                continue
            end = it.end.moment.at if not it.marker else it.start.moment.at + timedelta(minutes=1)
            end = max(end, it.start.moment.at + timedelta(minutes=1))
            label = mermaid_text(f"{it.label} {it.title}" if it.label.startswith("+") else it.title)
            if it.start.approx or it.end.approx:
                label = "≈ " + label
            if it.marker:
                plan_lines.append(
                    f"    {label} :milestone, {_mid(it.key)}, {_wall(it.start.moment.at, off)}, 0m"
                )
                continue
            plan_lines.append(
                f"    {label} :done, {_mid(it.key)}, {_wall(it.start.moment.at, off)}, "
                f"{_wall(end, off)}"
            )
        if plan_lines:
            lines += ["    section Planning", *plan_lines]
        phase_lines = []
        for p in tl.phases:
            assert p.start is not None
            p_end = phase_end(p, as_of)
            if p.start.moment.at > seg.end or max(p_end, p.start.moment.at) < seg.start:
                continue
            lo = max(p.start.moment.at, seg.start)
            hi = max(min(p_end, seg.end), lo + timedelta(minutes=1))
            tag = "done" if p.status == "complete" else "active"
            label = mermaid_text(f"{p.id} {p.name}")  # backticks dropped by mermaid_text
            if p.start.approx or (p.finish and p.finish.approx and p.status == "complete"):
                label = "≈ " + label
            phase_lines.append(
                f"    {label} :{tag}, p{p.id}s{n}, {_wall(lo, off)}, {_wall(hi, off)}"
            )
            for k, w in enumerate(p.waits, 1):
                w_end = w.end.moment.at if w.end else as_of
                wlo, whi = max(w.start.moment.at, seg.start), min(w_end, seg.end)
                if whi < wlo:
                    continue
                whi = max(whi, wlo + timedelta(minutes=1))
                phase_lines.append(
                    f"    {mermaid_text(f'{p.id} {w.kind}')} :crit, p{p.id}w{k}s{n}, "
                    f"{_wall(wlo, off)}, {_wall(whi, off)}"
                )
        if phase_lines:
            lines += ["    section Phases", *phase_lines]
        lines.append("```")
        charts.append("\n".join(lines))
    return charts


def _mid(key: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "", key) or "x"


def _cell(v: Value | None, ref: Value | None) -> str:
    if v is None:
        return ""
    loc = v.moment.local()
    same_day = ref is not None and ref.moment.local().date() == loc.date()
    text = f"{loc:%H:%M}" if same_day else v.moment.stamp()
    return ("≈ " if v.approx else "") + text


def render_table(tl: Timeline) -> list[str]:
    assert tl.as_of is not None
    as_of = tl.as_of.at
    out = [
        "| Phase | Name | Started | Finished | Merged | Active | Blocked | Claim |",
        "|---|---|---|---|---|---:|---:|---|",
    ]
    for it in tl.planning:
        if not it.start:
            continue
        dur = (
            ""
            if it.marker
            else fmt_duration(it.end.moment.at - it.start.moment.at)
            if it.end
            else ""
        )
        pid = it.label if it.label.startswith("+") or it.label == "00" else "plan"
        out.append(
            f"| {pid} | {_md(it.title)} | {_cell(it.start, None)} | "
            f"{'' if it.marker else _cell(it.end, it.start)} |  | {dur} |  | n/a |"
        )
    for p in tl.phases:
        active, waited = active_time(p, as_of)
        open_bar = p.status != "complete"
        finished = (
            "(in progress)"
            if p.status == "in_progress"
            else "(blocked)"
            if open_bar
            else _cell(p.finish, p.start)
        )
        merged = (
            _cell(p.merged, p.finish or p.start)
            if p.merged
            else ("not merged yet" if p.status == "complete" else "")
        )
        claim = f"`{p.claim}`" if p.claim else ""
        out.append(
            f"| {p.id} | {_md(p.name)} | {_cell(p.start, None)} | {finished} | {merged} | "
            f"{fmt_duration(active)}{' so far' if open_bar else ''} | "
            f"{fmt_duration(waited) if waited else ''} | {claim} |"
        )
    return out


def _md(s: str) -> str:
    return s.replace("|", "\\|")


def render_totals(tl: Timeline, gap_minutes: int) -> list[str]:
    assert tl.as_of is not None
    as_of = tl.as_of.at
    segs = sessions(activity(tl, timedelta(minutes=gap_minutes)), timedelta(minutes=gap_minutes))
    first = min(s.start for s in segs)
    elapsed = as_of - first
    active = sum((active_time(p, as_of)[0] for p in tl.phases), timedelta(0))
    blocked = sum((active_time(p, as_of)[1] for p in tl.phases), timedelta(0))
    idle = sum((segs[i + 1].start - segs[i].end for i in range(len(segs) - 1)), timedelta(0))
    lines = [
        f"**Totals:** elapsed {fmt_duration(elapsed)} (first recorded start to "
        f"{tl.as_of.stamp()}) · "
        f"active phase time {fmt_duration(active)} (sum over phases) · "
        f"blocked or paused {fmt_duration(blocked) if blocked else '0 m'} · "
        f"idle {fmt_duration(idle) if idle else '0 m'} in {len(segs) - 1} gap(s) over "
        f"{gap_minutes} min."
    ]
    if tl.not_started:
        lines.append("")
        lines.append(f"**Not started:** {', '.join(tl.not_started)}.")
    if tl.not_shown:
        lines.append("")
        lines.append(f"**Not shown (no usable times):** {', '.join(tl.not_shown)}.")
    return lines


def render_block(tl: Timeline, gap_minutes: int, image: str | None) -> str:
    out: list[str] = []
    if image:
        out += [f"![{tl.prefix or 'Project'} timeline]({image})", ""]
    if tl.as_of is None:
        out.append("*No phase or planning session has recorded times yet.*")
        return "\n".join(out)
    out.append(
        f"*Generated from the Phase Log Timeline bullets and git, as of {tl.as_of.stamp()}. "
        f"≈ marks a time inferred from git or a heading. Idle gaps over {gap_minutes} min start "
        "a new chart below"
        + (" and are collapsed in the image" if image else "")
        + ". Regenerate with `python3 scripts/phase_timeline.py --write`; do not edit by hand.*"
    )
    for chart in render_mermaid(tl, gap_minutes):
        out += ["", chart]
    out += ["", *render_table(tl), "", *render_totals(tl, gap_minutes)]
    return "\n".join(out)


