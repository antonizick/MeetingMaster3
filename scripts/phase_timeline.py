_PLAN_NAME = re.compile(r"([A-Z][A-Z0-9]*)_IMPLEMENTATION_PLAN\.md")
_CLAUDE_PREFIX = re.compile(r"Project prefix:\s*`([A-Z][A-Z0-9]*)`")
_ID = re.compile(r"\d{2}[a-z]?")
_ICONS = {"⬜": "not_started", "🔄": "in_progress", "⛔": "blocked", "✅": "complete"}


class TimelineError(Exception):
    """A problem that stops the generator (exit code 2)."""


def locate_plan(repo: Path) -> tuple[Path, str | None]:
    """``(<plan path>, <prefix or None>)`` in the working tree, like ``phx``'s ``locate_plan``."""
    prefixed = sorted(p.name for p in repo.iterdir() if _PLAN_NAME.fullmatch(p.name))
    if len(prefixed) > 1:
        claude = repo / "CLAUDE.md"
        m = _CLAUDE_PREFIX.search(claude.read_text(encoding="utf-8")) if claude.is_file() else None
        chosen = [n for n in prefixed if m and n == f"{m.group(1)}_IMPLEMENTATION_PLAN.md"]
        if len(chosen) != 1:
            raise TimelineError(f"several plans and no matching prefix in CLAUDE.md: {prefixed}")
        prefixed = chosen
    if prefixed:
        m2 = _PLAN_NAME.fullmatch(prefixed[0])
        return repo / prefixed[0], m2.group(1) if m2 else None
    if (repo / "IMPLEMENTATION_PLAN.md").is_file():
        return repo / "IMPLEMENTATION_PLAN.md", None
    raise TimelineError(f"no <PREFIX>_IMPLEMENTATION_PLAN.md or IMPLEMENTATION_PLAN.md in {repo}")


def sort_key(phase_id: str) -> tuple[int, str]:
    return int(phase_id[:2]), phase_id[2:]


def _cells(line: str) -> list[str]:
    body = line.strip()
    if body.startswith("|"):
        body = body[1:]
    if body.endswith("|"):
        body = body[:-1]
    return [c.strip() for c in re.split(r"(?<!\\)\|", body)]


@dataclass
class TableRow:
    id: str
    name: str
    status: str
    deps: tuple[str, ...]


def parse_phase_table(lines: list[str]) -> tuple[list[TableRow], int]:
    """Rows of the first table whose header has ``Phase`` and ``Status``; and its last line."""
    i = 0
    while i < len(lines):
        if lines[i].lstrip().startswith("|") and i + 1 < len(lines):
            header = [c.lower() for c in _cells(lines[i])]
            if "phase" in header and "status" in header and "---" in lines[i + 1]:
                return _table_rows(lines, i, header)
        i += 1
    raise TimelineError("no phase table (a table with 'Phase' and 'Status' columns)")


def _table_rows(lines: list[str], i: int, header: list[str]) -> tuple[list[TableRow], int]:
    col = header.index
    name_col = (
        col("phase name") if "phase name" in header else col("name") if "name" in header else None
    )
    deps_col = next((j for j, h in enumerate(header) if h.startswith("depends")), None)
    rows: list[TableRow] = []
    j = i + 2
    while j < len(lines) and lines[j].lstrip().startswith("|"):
        cells = _cells(lines[j])
        pid = cells[col("phase")].strip("` ") if len(cells) > col("phase") else ""
        if _ID.fullmatch(pid):
            rows.append(
                TableRow(
                    pid,
                    cells[name_col] if name_col is not None and name_col < len(cells) else "",
                    _status(cells[col("status")] if col("status") < len(cells) else ""),
                    tuple(_ID.findall(cells[deps_col])) if deps_col is not None else (),
                )
            )
        j += 1
    return rows, j - 1


def _status(cell: str) -> str:
    for icon, status in _ICONS.items():
        if icon in cell:
            return status
    low = cell.lower()
    for word, status in (
        ("in progress", "in_progress"),
        ("blocked", "blocked"),
        ("not started", "not_started"),
        ("complete", "complete"),
        ("done", "complete"),
    ):
        if word in low:
            return status
    return "not_started"


@dataclass
class LogEntry:
    line: int
    heading_ts: str  # "YYYY-MM-DD" or "YYYY-MM-DD HH:MM TZ"
    title: str
    timeline: str | None


_HEADING = re.compile(r"^###\s+(\d{4}-\d{2}-\d{2}(?: \d{2}:\d{2}(?: \S+)?)?)\s*:\s*(.+)$")
_TIMELINE_BULLET = re.compile(r"^\s*[-*]\s+\*\*Timeline:?\*\*:?\s*(.*)$")


def parse_phase_log(lines: list[str]) -> list[LogEntry]:
    start = next((i for i, ln in enumerate(lines) if re.match(r"^##\s+Phase Log", ln)), None)
    if start is None:
        return []
    entries: list[LogEntry] = []
    current: LogEntry | None = None
    for i in range(start + 1, len(lines)):
        ln = lines[i]
        if re.match(r"^##\s", ln):
            break
        m = _HEADING.match(ln)
        if m:
            current = LogEntry(i + 1, m.group(1), m.group(2).strip(), None)
            entries.append(current)
            continue
        if current is not None and current.timeline is None:
            t = _TIMELINE_BULLET.match(ln)
            if t:
                current.timeline = t.group(1).strip()
    return entries


