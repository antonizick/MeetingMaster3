@dataclass
class Value:
    moment: Moment
    approx: bool
    source: str  # "timeline", "git", "heading"


@dataclass
class Wait:
    kind: str  # "blocked" or "paused"
    start: Value
    end: Value | None  # None: still open


@dataclass
class PhaseRecord:
    id: str
    name: str
    status: str
    start: Value | None = None
    finish: Value | None = None
    merged: Value | None = None
    waits: list[Wait] = field(default_factory=list)
    claim: str | None = None


@dataclass
class PlanningItem:
    key: str  # stable id
    label: str  # short lane label
    title: str  # table text
    start: Value | None
    end: Value | None
    marker: bool = False  # a point (preflight) rather than a span


@dataclass
class Timeline:
    prefix: str | None
    phases: list[PhaseRecord]
    planning: list[PlanningItem]
    not_started: list[str]
    not_shown: list[str]
    as_of: Moment | None
    zones: list[str]


def _segments(text: str) -> list[str]:
    return [s.strip() for s in re.split(r"\s+·\s+", text) if s.strip()]


def _hash_in(seg: str) -> str | None:
    m = re.search(r"\((?:claim|merge) commit `?([0-9a-f]{7,40})`?\)", seg)
    return m.group(1) if m else None


class Builder:
    def __init__(self, rows: list[TableRow], entries: list[LogEntry], commits: list[Commit]):
        self.rows = rows
        self.entries = entries
        self.commits = commits  # newest first
        self.clock = Clock(commits)
        self.by_hash = {}
        for c in commits:
            self.by_hash[c.short] = c
            self.by_hash[c.sha] = c
        self._learn_zones()

    def _commit(self, ref: str | None) -> Commit | None:
        if not ref:
            return None
        hit = self.by_hash.get(ref)
        if hit:
            return hit
        return next((c for c in self.commits if c.sha.startswith(ref)), None)

    def _learn_zones(self) -> None:
        for e in self.entries:
            for seg in _segments(e.timeline or ""):
                m = _TS_RE.search(seg)
                if m:
                    self.clock.learn(m.group(1), self._commit(_hash_in(seg)))
        for c in self.commits:
            m = re.search(rf"preflight ({_TS})", c.subject)
            if m:
                self.clock.learn(m.group(1), c)

    def value(self, text: str, source: str = "timeline", approx: bool = False) -> Value | None:
        mo = self.clock.parse(text)
        return Value(mo, approx, source) if mo else None

    def git_value(self, c: Commit | None, approx: bool) -> Value | None:
        return Value(self.clock.from_commit(c), approx, "git") if c else None

    # ---- per-phase git lookups ---------------------------------------------------------
    def _subject_matches(self, pattern: str) -> list[Commit]:
        rx = re.compile(pattern, re.I)
        return [c for c in self.commits if rx.search(c.subject)]

    def claim_commit(self, pid: str) -> Commit | None:
        hits = self._subject_matches(rf"^chore\(plan\): start phase {pid}\b")
        return hits[-1] if hits else None  # oldest

    def merge_commit(self, pid: str) -> Commit | None:
        hits = [
            c
            for c in self._subject_matches(rf"^Merge (?:phase {pid}\b|branch '?phase-{pid}-)")
            if len(c.parents) > 1
        ]
        return hits[0] if hits else None  # newest

    def mentions(self, pid: str) -> list[Commit]:
        """Commits whose subject says they are work on the phase (not just a prompt edit)."""
        p = rf"phase[- ]{pid}(?![0-9a-z])"
        work = (
            rf"\({p}\)|\bcomplete {p}|\b{p}:? complete|\b{p}[:,] |\b{p} (?:log|close)"
            rf"|\b{p} wip|^wip\({p}\)|close[ -]?out (?:of )?{p}|\b{p} \("
        )
        return [c for c in self._subject_matches(work) if len(c.parents) <= 1]

    def next_claim_after(self, pid: str, at: datetime) -> datetime | None:
        times = [
            c.at
            for c in self._subject_matches(r"^chore\(plan\): start phase ")
            if c.at > at and not re.search(rf"start phase {pid}\b", c.subject)
        ]
        return min(times) if times else None

    # ---- build -------------------------------------------------------------------------
    def build(self, prefix: str | None) -> Timeline:
        phases: list[PhaseRecord] = []
        not_shown: list[str] = []
        not_started: list[str] = []
        planning: list[PlanningItem] = []
        status_of = {r.id: r for r in self.rows}
        for row in sorted(self.rows, key=lambda r: sort_key(r.id)):
            rec = self.phase(row)
            if row.id == "00":
                item = self.phase00(rec)
                if item:
                    planning.append(item)
                elif row.status != "not_started":
                    not_shown.append("00")
                continue
            if rec.start is None:
                (not_started if row.status == "not_started" else not_shown).append(row.id)
                continue
            if row.status == "complete" and rec.finish is None and rec.merged is None:
                not_shown.append(f"{row.id} (finish unknown)")
                continue
            phases.append(rec)
        planning += self.planning_entries(not_shown)
        planning += self.preflights()
        planning.sort(key=lambda p: (p.start.moment.at if p.start else _EPOCH, p.key))
        del status_of
        used: list[Moment] = []
        for p in phases:
            used += [v.moment for v in (p.start, p.finish, p.merged) if v]
            for w in p.waits:
                used += [v.moment for v in (w.start, w.end) if v]
        for it in planning:
            used += [v.moment for v in (it.start, it.end) if v]
        as_of: Moment | None = None
        if used:
            latest = max(used, key=lambda m: m.at)
            as_of = Moment(latest.at, self.clock.zone_for(latest.at))
        zones = sorted({m.zone for m in used})
        return Timeline(prefix, phases, planning, not_started, not_shown, as_of, zones)

    def phase(self, row: TableRow) -> PhaseRecord:
        rec = PhaseRecord(row.id, row.name, row.status)
        if row.status == "not_started":
            return rec
        heading: str | None = None
        for e in self.entries:
            m = re.match(rf"Phase {row.id}\s*:", e.title)
            if not m:
                continue
            heading = e.heading_ts
            if e.timeline:
                self._apply_bullet(rec, e.timeline)
        self._git_fallbacks(rec, heading)
        return rec

    def _apply_bullet(self, rec: PhaseRecord, text: str) -> None:
        for seg in _segments(text):
            low = seg.lower()
            ts = _TS_RE.findall(seg)
            if low.startswith("started") and ts:
                rec.start = self.value(ts[0])
                rec.claim = _hash_in(seg) or rec.claim
            elif low.startswith("finished") and ts:
                rec.finish = self.value(ts[0])
            elif low.startswith("merged") and ts:
                rec.merged = self.value(ts[0])
            elif low.startswith(("blocked", "paused")) and ts:
                kind = "paused" if low.startswith("paused") else "blocked"
                start = self.value(ts[0])
                end = self.value(ts[1]) if len(ts) > 1 else None
                if start is None:
                    continue
                rec.waits = [w for w in rec.waits if w.start.moment.at != start.moment.at]
                rec.waits.append(Wait(kind, start, end))
        rec.waits.sort(key=lambda w: w.start.moment.at)

    def _git_fallbacks(self, rec: PhaseRecord, heading: str | None) -> None:
        claim = self.claim_commit(rec.id)
        merge = self.merge_commit(rec.id)
        if rec.start is None:
            if claim:
                rec.start = self.git_value(claim, approx=False)
            else:
                mentions = self.mentions(rec.id)
                rec.start = self.git_value(mentions[-1] if mentions else None, approx=True)
        if rec.claim is None and claim:
            rec.claim = claim.short
        if rec.merged is None and merge:
            rec.merged = self.git_value(merge, approx=False)
        if not rec.waits:
            self._git_waits(rec)
        if rec.status == "blocked" and not any(w.end is None for w in rec.waits):
            blocks = self._subject_matches(rf"^chore\(plan\): phase {rec.id} blocked")
            anchor = self.git_value(blocks[0], approx=False) if blocks else None
            anchor = anchor or rec.finish or rec.start
            if anchor:
                rec.waits.append(Wait("blocked", Value(anchor.moment, True, "git"), None))
        if rec.status != "complete" or rec.finish is not None:
            return
        candidates: list[Commit] = []
        if merge and len(merge.parents) > 1:
            tip = self._commit(merge.parents[1])
            if tip:
                candidates.append(tip)
        candidates += [c for c in self.mentions(rec.id) if claim is None or c.sha != claim.sha]
        if rec.merged:
            candidates = [c for c in candidates if c.at <= rec.merged.moment.at]
        if rec.start:
            candidates = [c for c in candidates if c.at >= rec.start.moment.at]
        if candidates:
            rec.finish = self.git_value(max(candidates, key=lambda c: c.at), approx=True)
        elif heading and " " in heading:
            rec.finish = self.value(heading, source="heading", approx=True)
        elif rec.merged:
            rec.finish = Value(rec.merged.moment, True, "git")
        elif rec.start:
            # last resort: the end of the burst of commits that follows the claim, before
            # another phase is claimed (a pause of more than BURST_GAP ends the burst)
            bound = self.next_claim_after(rec.id, rec.start.moment.at)
            last: Commit | None = None
            at = rec.start.moment.at
            for c in sorted(self.commits, key=lambda c: c.at):
                if c.at <= rec.start.moment.at or (bound is not None and c.at >= bound):
                    continue
                if c.at - at > BURST_GAP:
                    break
                last, at = c, c.at
            if last is not None:
                rec.finish = self.git_value(last, approx=True)
        if rec.finish and rec.start and rec.finish.moment.at < rec.start.moment.at:
            rec.finish = None

    def _git_waits(self, rec: PhaseRecord) -> None:
        events = self._subject_matches(
            rf"^chore\(plan\): (?:phase {rec.id} blocked|resume phase {rec.id}\b)"
        )
        open_wait: Wait | None = None
        for c in reversed(events):  # oldest first
            if "blocked" in c.subject.lower():
                if open_wait is None:
                    v = self.git_value(c, approx=False)
                    if v:
                        open_wait = Wait("blocked", v, None)
                        rec.waits.append(open_wait)
            elif open_wait is not None:
                open_wait.end = self.git_value(c, approx=False)
                open_wait = None

    def phase00(self, rec: PhaseRecord) -> PlanningItem | None:
        start, end = rec.start, rec.finish
        if start is None and self.commits:
            root = self.commits[-1]
            end = end or self.git_value(root, approx=True)
            return PlanningItem("p00", "00", rec.name, end, end, marker=True)
        if start is None:
            return None
        return PlanningItem("p00", "00", rec.name, start, end or start)

    def planning_entries(self, not_shown: list[str]) -> list[PlanningItem]:
        items: list[PlanningItem] = []
        n = 0
        for e in self.entries:
            m = re.match(r"Planning\s*:\s*(.+?)(?:\s*\([^()]*\))?$", e.title)
            if not m:
                continue
            n += 1
            title = m.group(1).strip()
            title = title[:1].upper() + title[1:]
            ids = [i for i in _ID.findall(title) if re.search(rf"\b{i}\b", title)]
            label = "+" + ", ".join(ids) if ids else "plan"
            start = end = None
            for seg in _segments(e.timeline or ""):
                ts = _TS_RE.findall(seg)
                if seg.lower().startswith("started") and ts:
                    start = self.value(ts[0])
                elif seg.lower().startswith("finished") and ts:
                    end = self.value(ts[0])
            key = f"plan{n}"
            if start and end:
                items.append(PlanningItem(key, label, title, start, end))
            elif start or end or " " in e.heading_ts:
                one = start or end or self.value(e.heading_ts, source="heading", approx=True)
                if one:
                    items.append(PlanningItem(key, label, title, one, one, marker=True))
            else:
                not_shown.append(f"planning {e.heading_ts} ({label})")
        return items

    def preflights(self) -> list[PlanningItem]:
        out = []
        for c in reversed(self._subject_matches(r"^docs\(plan\): phx preflight")):
            v = self.git_value(c, approx=False)
            out.append(PlanningItem(f"pf-{c.short}", "preflight", "phx preflight", v, v, True))
        return out


