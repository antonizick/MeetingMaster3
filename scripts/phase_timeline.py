# Fallback offsets (minutes east of UTC). Offsets learned from git commits win over this table.
_KNOWN_ZONES = {
    "UTC": 0, "GMT": 0, "Z": 0, "WET": 0, "WEST": 60, "BST": 60, "CET": 60, "CEST": 120,
    "EET": 120, "EEST": 180, "MSK": 180, "JST": 540, "KST": 540, "AEST": 600, "AEDT": 660,
    "NZST": 720, "NZDT": 780, "HST": -600, "AKST": -540, "AKDT": -480, "PST": -480,
    "PDT": -420, "MST": -420, "MDT": -360, "CST": -360, "CDT": -300, "EST": -300, "EDT": -240,
    "AST": -240, "ADT": -180, "NST": -210, "NDT": -150,
}  # fmt: skip

_TS = r"\d{4}-\d{2}-\d{2} \d{2}:\d{2}(?: (?:[A-Z]{1,5}|[+-]\d{2}:?\d{2}))?"
_TS_RE = re.compile(rf"({_TS})")
_TS_PARTS = re.compile(r"(\d{4})-(\d{2})-(\d{2}) (\d{2}):(\d{2})(?: (\S+))?")
_WEEKDAYS = ("Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun")
