class Axis:
    """Maps instants to x, with idle gaps collapsed into fixed-width breaks.

    Each working session gets a width proportional to the square root of its length, so a short
    session stays readable next to a long one; inside a session the scale is linear.
    """

    def __init__(self, segs: list[Span], x0: float, x1: float) -> None:
        pad = timedelta(minutes=3)
        self.view = [Span(s.start - pad, s.end + pad) for s in segs]
        n_breaks = len(segs) - 1
        self.brk = min(BREAK_W, max(18.0, 0.3 * (x1 - x0) / n_breaks)) if n_breaks else BREAK_W
        usable = (x1 - x0) - self.brk * n_breaks
        mins = [max((v.end - v.start).total_seconds() / 60, 1.0) for v in self.view]
        weights = [m**0.5 for m in mins]
        total = sum(weights)
        widths: list[float] = [usable * w / total for w in weights]
        self.ppm: list[float] = [w / m for w, m in zip(widths, mins)]
        self.x0 = x0
        self.starts: list[float] = []
        x = x0
        for w in widths:
            self.starts.append(x)
            x += w + self.brk
        self.widths = widths

    def x(self, at: datetime) -> float:
        for i, v in enumerate(self.view):
            if at <= v.end or i == len(self.view) - 1:
                at = min(max(at, v.start), v.end)
                return self.starts[i] + (at - v.start).total_seconds() / 60 * self.ppm[i]
        return self.x0  # pragma: no cover

    def seg_end_x(self, i: int) -> float:
        return self.starts[i] + self.widths[i]


