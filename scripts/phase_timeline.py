@dataclass(frozen=True)
class Moment:
    """An instant (aware, minute precision) and the zone label it is shown in."""

    at: datetime
    zone: str

    def local(self) -> datetime:
        return self.at.astimezone(_tz(self.at.utcoffset()))

    def stamp(self) -> str:
        return f"{self.local():%Y-%m-%d %H:%M} {self.zone}"


def _tz(off: timedelta | None) -> timezone:
    return timezone(off or timedelta(0))


def _zone_name(off: timedelta, names: dict[int, str]) -> str:
    minutes = int(off.total_seconds() // 60)
    if minutes in names:
        return names[minutes]
    sign = "+" if minutes >= 0 else "-"
    return f"UTC{sign}{abs(minutes) // 60:02d}:{abs(minutes) % 60:02d}"


@dataclass(frozen=True)
class Commit:
    sha: str
    short: str
    at: datetime  # aware, truncated to the minute
    parents: tuple[str, ...]
    subject: str


class Clock:
    """Turns ``YYYY-MM-DD HH:MM TZ`` into instants, using offsets git reports where it can."""

    def __init__(self, commits: list[Commit]) -> None:
        self.commits = commits
        self.learned: dict[str, int] = {}
        self.names: dict[int, str] = {}
        self.seen: list[str] = []  # zone abbreviations written anywhere in the plan

    def saw(self, text: str) -> None:
        for z in re.findall(r"\d{2}:\d{2} ([A-Z]{2,5})\b", text):
            if z in _KNOWN_ZONES and z not in self.seen:
                self.seen.append(z)

    def learn(self, text: str, commit: Commit | None) -> None:
        m = _TS_PARTS.fullmatch(text)
        if not m or commit is None or not m.group(6) or not m.group(6).isalpha():
            return
        off = commit.at.utcoffset()
        wall = commit.at.replace(tzinfo=None)
        if off is not None and wall == _naive(m) and m.group(6) not in self.learned:
            self.learned[m.group(6)] = int(off.total_seconds() // 60)

    def parse(self, text: str) -> Moment | None:
        m = _TS_PARTS.fullmatch(text.strip())
        if not m:
            return None
        naive = _naive(m)
        zone = m.group(6)
        minutes: int | None = None
        if zone and re.fullmatch(r"[+-]\d{2}:?\d{2}", zone):
            sign = -1 if zone[0] == "-" else 1
            digits = zone[1:].replace(":", "")
            minutes = sign * (int(digits[:2]) * 60 + int(digits[2:]))
        elif zone:
            minutes = self.learned.get(zone, _KNOWN_ZONES.get(zone))
        if minutes is None:
            minutes = self._nearest_offset(naive)
        at = naive.replace(tzinfo=timezone(timedelta(minutes=minutes)))
        label = zone if zone and zone.isalpha() else _zone_name(timedelta(minutes=minutes), {})
        self.names.setdefault(minutes, label)
        return Moment(at, label)

    def from_commit(self, commit: Commit) -> Moment:
        return Moment(commit.at, self.zone_for(commit.at))

    def zone_for(self, at: datetime) -> str:
        """The label for ``at``'s offset: as written in the plan, else ``UTC±HH:MM``."""
        off = at.utcoffset() or timedelta(0)
        minutes = int(off.total_seconds() // 60)
        known = {v: k for k, v in sorted(self.learned.items())}
        seen = next((z for z in self.seen if _KNOWN_ZONES[z] == minutes), None)
        return self.names.get(minutes) or known.get(minutes) or seen or _zone_name(off, {})

    def _nearest_offset(self, naive: datetime) -> int:
        if not self.commits:
            return 0
        best = min(self.commits, key=lambda c: abs(c.at.replace(tzinfo=None) - naive))
        off = best.at.utcoffset() or timedelta(0)
        return int(off.total_seconds() // 60)


def _naive(m: re.Match[str]) -> datetime:
    y, mo, d, h, mi = (int(m.group(i)) for i in range(1, 6))
    return datetime(y, mo, d, h, mi)


def fmt_duration(delta: timedelta) -> str:
    minutes = round(delta.total_seconds() / 60)
    if minutes < 1:
        return "< 1 m"
    if minutes < 60:
        return f"{minutes} m"
    hours, mins = divmod(minutes, 60)
    if hours < 24:
        return f"{hours} h {mins} m" if mins else f"{hours} h"
    days, hours = divmod(hours, 24)
    return f"{days} d {hours} h" if hours else f"{days} d"


# ------------------------------------------------------------------------------------------- git


def git_commits(repo: Path) -> list[Commit]:
    """Commits reachable from ``HEAD``, newest first (empty outside git or before the first)."""
    try:
        out = subprocess.run(
            ["git", "-C", str(repo), "log", "HEAD", "--format=%H%x1f%h%x1f%cI%x1f%P%x1f%s"],
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError:
        return []
    if out.returncode != 0:
        return []
    commits = []
    for line in out.stdout.splitlines():
        parts = line.split("\x1f")
        if len(parts) != 5:
            continue
        at = datetime.fromisoformat(parts[2]).replace(second=0, microsecond=0)
        commits.append(Commit(parts[0], parts[1], at, tuple(parts[3].split()), parts[4]))
    return commits


