"""Readable transcript (``YYYY-MM-DD - Title (Transcript).md``): writer only (R25, ADR-0031).

A people-first copy of the companion transcript, laid out like the review screen::

    ---
    mm3-id: <uuid>
    mm3-kind: readable-transcript
    mm3-note: "[[2026-10-11 - Product Sync]]"
    mm3-transcript: "[[2026-10-11 - Product Sync.transcript]]"
    duration: "0:42:17"
    language: en
    speakers:
      - Alice
    ---
    <span style="...">Generated by MeetingMaster3 ...</span>

    <span style="color: var(--text-muted)">04:14</span> <mark style="background: ...">Alice</mark>
    Good morning, everyone.

Each speaker keeps one highlight colour, in the review screen's palette order. A turn longer than
:data:`PARAGRAPH_SECONDS` is split into paragraphs at segment boundaries. Spoken text is
neutralised so it can never become HTML, a wikilink, an embed, a tag, a comment or a section
marker (S3).

The file is generated from the companion and is never parsed back: the companion stays the source
of truth (ADR-0009), and edits made here are replaced the next time it is written.
"""

from __future__ import annotations

import re
from typing import Any

from meetingmaster3.domain.transcript import CompanionTranscript, Segment, group_turns
from meetingmaster3.markdown.frontmatter import render_frontmatter, wikilink
from meetingmaster3.markdown.transcript_format import duration_text

KIND = "readable-transcript"
"""Value of ``mm3-kind`` that marks the file; vault scanners classify by it (not by name)."""
PARAGRAPH_SECONDS = 90.0
"""A turn is split into a new paragraph once the current one runs longer than this."""
SPEAKER_COLOURS = (
    "rgba(122,162,255,.35)",
    "rgba(253,186,116,.35)",
    "rgba(134,239,172,.35)",
    "rgba(216,180,254,.35)",
    "rgba(253,164,175,.35)",
    "rgba(103,232,249,.35)",
    "rgba(253,224,71,.35)",
    "rgba(190,242,100,.35)",
)
"""The review screen's ``.spk-0`` ... ``.spk-7`` colours (``app.css``, dark variants) as
translucent highlights, so the text keeps the theme's own colour in light and dark themes."""
NEUTRAL = "rgba(148,163,184,.30)"
"""Highlight for speakers without a name (``Speaker 3``) and for undiarized text."""
MUTED = "color: var(--text-muted)"
NOTICE = (
    "Generated by MeetingMaster3 for reading. Edits made here are replaced when the transcript "
    "changes; the full-fidelity copy is the companion transcript linked in this file's "
    "properties."
)

_HTML = {"&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;"}
# Markdown and Obsidian syntax characters: emphasis, code, links and embeds, tags, math,
# comments (%%), highlights (==), strikethrough, block references, tables and escapes.
_MD_PUNCT = re.compile(r"([\\`*_\[\]#$%=~^|])")
_LINE_START = re.compile(r"^(\s*)([-+>]|\d+[.)])")


def clock(seconds: float) -> str:
    """``mm:ss``, or ``h:mm:ss`` from one hour (as ``review/workspace.py:clock``)."""
    total = int(max(seconds, 0))
    h, rest = divmod(total, 3600)
    m, s = divmod(rest, 60)
    return f"{h}:{m:02d}:{s:02d}" if h else f"{m:02d}:{s:02d}"


def neutralise(text: str) -> str:
    """Spoken ``text`` as inert Markdown: HTML characters become entities, Markdown and Obsidian
    punctuation is backslash-escaped, and a leading list or quote marker is escaped."""
    text = " ".join(text.split())
    text = "".join(_HTML.get(c, c) for c in text)
    text = _MD_PUNCT.sub(r"\\\1", text)
    return _LINE_START.sub(lambda m: m[1] + "\\" + m[2], text)


def _html(text: str) -> str:
    return "".join(_HTML.get(c, c) for c in " ".join(text.split()))


def _paragraphs(segments: list[Segment], limit: float) -> list[str]:
    paragraphs: list[list[str]] = []
    start = 0.0
    for seg in segments:
        words = " ".join(seg.text.split())
        if not words:
            continue
        if not paragraphs or seg.start - start >= limit:
            paragraphs.append([])
            start = seg.start
        paragraphs[-1].append(words)
    return [neutralise(" ".join(p)) for p in paragraphs]


def colour_map(doc: CompanionTranscript) -> dict[str, int]:
    """Palette index per label, the same as the review screen (natural label order). Labels
    that carry the same name (one person split by diarization) share the first one's colour."""
    labels = doc.transcript.speaker_labels
    by_name: dict[str, int] = {}
    out: dict[str, int] = {}
    for i, label in enumerate(labels):
        name = doc.speakers.names.get(label)
        index = i % len(SPEAKER_COLOURS)
        out[label] = by_name.setdefault(name, index) if name else index
    return out


def render_body(doc: CompanionTranscript, *, paragraph_seconds: float = PARAGRAPH_SECONDS) -> str:
    nl = doc.newline
    labels = doc.transcript.speaker_labels
    colours = colour_map(doc)
    parts = [f'<span style="{MUTED}; font-size: smaller">{NOTICE}</span>{nl}{nl}']
    turns = group_turns(doc.transcript)
    for turn in turns:
        name = doc.speakers.display_name(turn.speaker_label, labels)
        label = turn.speaker_label
        named = label is not None and label in doc.speakers.names
        background = SPEAKER_COLOURS[colours[label]] if named and label else NEUTRAL
        heading = (
            f'<span style="{MUTED}">{clock(turn.start)}</span> '
            f'<mark style="background: {background}; font-weight: 600">{_html(name)}</mark>'
        )
        paragraphs = _paragraphs(turn.segments, paragraph_seconds) or [""]
        parts.append(heading + nl + (nl + nl).join(paragraphs).rstrip() + nl + nl)
    if not turns:
        parts.append(f"_No speech was detected._{nl}")
    return "".join(parts).rstrip("\r\n") + nl


def frontmatter_data(
    doc: CompanionTranscript, *, note_link: str | None, transcript_link: str | None
) -> dict[str, Any]:
    t = doc.transcript
    labels = t.speaker_labels
    speakers = list(dict.fromkeys(doc.speakers.display_name(label, labels) for label in labels))
    data: dict[str, Any] = {
        "mm3-id": str(doc.meeting_id),
        "mm3-kind": KIND,
        "mm3-note": wikilink(note_link) if note_link else None,
        "mm3-transcript": wikilink(transcript_link) if transcript_link else None,
        "duration": duration_text(t.duration) if t.duration is not None else None,
        "language": t.language,
        "speakers": speakers or None,
    }
    return {k: v for k, v in data.items() if v is not None}


def render_readable(
    doc: CompanionTranscript,
    *,
    note_link: str | None = None,
    transcript_link: str | None = None,
    paragraph_seconds: float = PARAGRAPH_SECONDS,
) -> str:
    """The whole readable file for ``doc``. ``note_link`` and ``transcript_link`` are wikilink
    targets (without brackets); ``note_link`` defaults to the companion's own ``mm3-note``."""
    fm = render_frontmatter(
        frontmatter_data(doc, note_link=note_link or doc.note_ref, transcript_link=transcript_link),
        newline=doc.newline,
    )
    return fm + render_body(doc, paragraph_seconds=paragraph_seconds)
